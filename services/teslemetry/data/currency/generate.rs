//! Offline extractor for the exact, checksum-verified sources in README.md.
use std::{collections::BTreeMap, env, fmt::Write, fs};

fn attribute<'a>(line: &'a str, name: &str) -> Option<&'a str> {
    line.split_once(&format!(" {name}=\""))?
        .1
        .split_once('"')
        .map(|v| v.0)
}

fn code(value: &str, length: usize) -> &str {
    assert!(value.len() == length && value.bytes().all(|v| v.is_ascii_uppercase()));
    value
}

fn date(value: Option<&str>, default: u32) -> u32 {
    let Some(value) = value else { return default };
    assert!(value.len() == 10 && value.as_bytes()[4] == b'-' && value.as_bytes()[7] == b'-');
    let year: u32 = value[..4].parse().unwrap();
    let month: u32 = value[5..7].parse().unwrap();
    let day: u32 = value[8..].parse().unwrap();
    let leap = year % 4 == 0 && (year % 100 != 0 || year % 400 == 0);
    let days = match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 => {
            if leap {
                29
            } else {
                28
            }
        }
        _ => panic!("invalid month"),
    };
    assert!((1..=days).contains(&day));
    year * 10000 + month * 100 + day
}

fn main() {
    let args: Vec<String> = env::args().collect();
    assert_eq!(
        args.len(),
        4,
        "usage: generate zone.tab supplementalData.xml output.rs"
    );
    let zones = fs::read_to_string(&args[1]).unwrap();
    let mut xml = fs::read_to_string(&args[2]).unwrap();
    assert!(zones.len() < 100_000 && xml.len() < 1_000_000);
    while let Some(start) = xml.find("<!--") {
        let end = start + xml[start..].find("-->").expect("unclosed XML comment") + 3;
        xml.replace_range(start..end, "");
    }
    let mut zone_map = BTreeMap::new();
    for line in zones
        .lines()
        .filter(|v| !v.is_empty() && !v.starts_with('#'))
    {
        let fields: Vec<&str> = line.split('\t').collect();
        assert!((3..=4).contains(&fields.len()));
        let region = code(fields[0], 2);
        let zone = fields[2];
        assert!(
            zone.len() < 128
                && zone
                    .bytes()
                    .all(|v| v.is_ascii_alphanumeric() || b"/_+-".contains(&v))
        );
        assert!(zone_map.insert(zone, region).is_none());
    }
    let mut output = String::from("// Generated by data/currency/generate.rs; sources and licenses: data/currency/README.md.\n#[rustfmt::skip]\nconst ZONES: &[(&str, &str)] = &[\n");
    for (zone, region) in &zone_map {
        writeln!(output, "    ({zone:?}, {region:?}),").unwrap();
    }
    output.push_str("];\n#[rustfmt::skip]\nconst CURRENCIES: &[(&str, &str, u32, u32)] = &[\n");
    let currency_data = xml
        .split_once("<currencyData>")
        .unwrap()
        .1
        .split_once("</currencyData>")
        .unwrap()
        .0;
    let mut region = None;
    let mut records = Vec::new();
    for line in currency_data.lines().map(str::trim) {
        if line.starts_with("<region ") {
            region = Some(code(attribute(line, "iso3166").unwrap(), 2));
        } else if line == "</region>" {
            region = None;
        } else if line.starts_with("<currency ") {
            let territory = region.unwrap();
            let currency = code(attribute(line, "iso4217").unwrap(), 3);
            assert!(line.ends_with("/>"));
            match attribute(line, "tender") {
                Some("false") => continue,
                None | Some("true") => (),
                _ => panic!("invalid tender attribute"),
            }
            let from = date(attribute(line, "from"), 0);
            let to = date(attribute(line, "to"), 99991231);
            assert!(from <= to);
            // A date-only API cannot interpret a transition in a different local zone.
            for key in ["tz", "to-tz"] {
                if let Some(zone) = attribute(line, key) {
                    assert_eq!(zone_map.get(zone), Some(&territory));
                    assert_eq!(
                        zone_map
                            .values()
                            .filter(|value| **value == territory)
                            .count(),
                        1
                    );
                }
            }
            // Preserve all tender intervals, including overlaps; lookup decides ambiguity.
            if zone_map.values().any(|value| *value == territory) {
                records.push((territory, currency, from, to));
            }
        }
    }
    records.sort_unstable();
    assert!(zone_map.len() > 400 && records.len() > 400);
    for (region, currency, from, to) in records {
        writeln!(output, "    ({region:?}, {currency:?}, {from}, {to}),").unwrap();
    }
    output.push_str("];\n");
    fs::write(&args[3], output).unwrap();
}
